# -*- coding: utf-8 -*-
u"""The reversal predicate, as JavaScript, GENERATED from the Python one.

Chris, ruling 4 of 2026-10-25: *"refuse-to-save when the assembly equals the reverse of the
candidate"*.  That refusal has to run in the signing console, in the browser, against the string the
signer is assembling right now -- so the predicate exists on two axes: `signature_reversal.examine`
offline over recorded reads, and this one live over the tiles.

ONE RULE, TWO AXES.  A second hand-written implementation of the same rule is two rules that agree
until they do not, and this lane has already put a TRUE and a FALSE verdict about one uuid into one
record that way.  So nothing here is retyped:

  * the branch order and the vocabulary of flags come from `signature_reversal.examine`, ported once,
    in this one place, and `test_reversal_guard_js.py` runs the PORT under node against the PYTHON
    over every real signature/read pair plus a generated cross-product, and fails on any
    disagreement.  That test is a cross-implementation witness: node never calls Python, so it
    cannot agree by construction.
  * the confusable vocabulary is EMITTED from `confusable_vocab` at generation time.  When a pair is
    added there it is in the console's next render, and no one has to remember this file exists.

WHAT THIS DOES NOT SOLVE.  `reversed_exact` -- Chris's literal words, and the only flag the console
REFUSES on -- would not have caught the founding case.  `p442:n0` was signed רבך against pixels דבר:
a reversal AND a dalet read as a final kaf, so the assembly is at distance 1 from the reverse, not 0.
That is why the console also WARNS on the one-swap flags, and why the warning is a warning: a refusal
that fires on a suspect gets overridden by habit, and then it is not a refusal.

The guard is advisory about PIXELS in one more way: it compares two strings.  A signer who reverses
the span AND mis-tiles a glyph that the vocabulary does not carry gets `reversed_one_swap_unlisted`,
which is still only a shape.  Nothing here looks at a crop.

ALL PAGE NUMBERS ARE FILE PAGES (printed = file - 88).
"""
import hashlib
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import confusable_vocab as V                                             # noqa: E402
import signature_reversal as R                                           # noqa: E402

#: The register names `confusable_vocab.registers` can return, strongest first.  Emitted so the JS
#: table is built in the same order the Python returns; a born-test asserts the two agree per pair.
REGISTER_ORDER = ("SIGNED_GLYPH_CARD", "ADJUDICATED_IN_AUDIT", "ARGUED_SAME_DEFECT",
                  "OBSERVED_IN_READS")

#: The flags the console REFUSES a save on.  Chris's words name the first; the second is the same
#: mistake committed word by word instead of span-wide, which is not a different ruling.
REFUSING_FLAGS = ("reversed_exact", "reversed_per_word_exact")

#: The flags the console WARNS on.  A suspect, never a refusal -- see the module docstring.
WARNING_FLAGS = ("reversed_one_swap", "reversed_one_swap_unlisted")

assert set(REFUSING_FLAGS) | set(WARNING_FLAGS) == set(R.VERDICTS), \
    "a verdict in signature_reversal.VERDICTS has no consequence in the console, or vice versa: %r" \
    % (sorted(set(R.VERDICTS) ^ (set(REFUSING_FLAGS) | set(WARNING_FLAGS))),)


def _vocab_tables():
    u"""(registers, names) keyed by `confusable_vocab.key`, derived from that module, never typed.

    Every key the vocabulary knows is walked back through `registers()` and `name()`, so the tables
    carry exactly what the Python functions return and a disagreement is impossible to introduce by
    editing one of the two.
    """
    regs, names = {}, {}
    for k in sorted(V.ALL_WITNESSED):
        assert len(k) == 2, "a vocabulary key is not a consonant pair: %r" % (k,)
        a, b = k[0], k[1]
        assert V.key(a, b) == k, "key(%r, %r) is not %r" % (a, b, k)
        regs[k] = list(V.registers(a, b))
        assert all(r in REGISTER_ORDER for r in regs[k]), \
            "%r carries a register this module does not know: %r" % (k, regs[k])
        names[k] = V.name(a, b)
    return regs, names


REGISTERS, PAIR_NAMES = _vocab_tables()

# The JS. Written once, in one piece, so the branch order can be read against examine() side by side.
# Every `return` below matches a `return rec` there, in the same order, with the same flag string.
_JS_TEMPLATE = u"""
/* reversal guard -- GENERATED by reversal_guard_js.py from signature_reversal.examine and
   confusable_vocab.  Do not edit this block in the page: edit the generator and re-render.
   test_reversal_guard_js.py runs THIS code under node against the Python and fails on any
   disagreement, so an edit here that the generator does not know about is caught, not absorbed. */
var RG_REGISTERS=__REGISTERS__;
var RG_PAIRNAMES=__PAIRNAMES__;
var RG_REFUSING=__REFUSING__;
var RG_WARNING=__WARNING__;
function rgCons(s){
 var t=(s||"").normalize("NFC").replace(/[\\u0591-\\u05C7]/g,"");
 return t.match(/[\\u05D0-\\u05EA]/g)||[];}
function rgWords(s){
 var t=(s||"").normalize("NFC").replace(/[\\u0591-\\u05C7]/g,"");
 var parts=t.split(/[^\\u05D0-\\u05EA]+/),out=[],i;
 for(i=0;i<parts.length;i++){var c=rgCons(parts[i]);if(c.length)out.push(c);}
 return out;}
function rgRevAll(cs){return cs.slice().reverse();}
function rgRevPerWord(s){var ws=rgWords(s),out=[],i;
 for(i=0;i<ws.length;i++)out=out.concat(ws[i].slice().reverse());
 return out;}
function rgDiffs(a,b){if(a.length!==b.length)return null;
 var out=[],i;for(i=0;i<a.length;i++)if(a[i]!==b[i])out.push([i,a[i],b[i]]);
 return out;}
function rgKey(a,b){return [a,b].sort().join("");}
function rgRegisters(a,b){var k=rgKey(a,b);return RG_REGISTERS[k]?RG_REGISTERS[k].slice():[];}
function rgPairName(a,b){var k=rgKey(a,b);
 return (RG_PAIRNAMES[k]===undefined)?null:RG_PAIRNAMES[k];}
/* The port of signature_reversal.examine. Same branches, same order, same flag strings. */
function rgExamine(signature,read){
 var sig=rgCons(signature),rd=rgCons(read),rev=rgRevAll(sig),pw=rgRevPerWord(signature);
 var rec={signature_cons:sig.join(""),read_cons:rd.join(""),reverse_cons:rev.join(""),
  reverse_per_word_cons:pw.join(""),n_cons:sig.length,dist_to_signature:null,dist_to_reverse:null,
  swap:null,registers:[],flag:null};
 if(!rd.length){rec.flag="empty_read";return rec;}
 if(!sig.length){rec.flag="empty_signature";return rec;}
 var dF=rgDiffs(sig,rd),dR=rgDiffs(rev,rd);
 rec.dist_to_signature=(dF===null)?null:dF.length;
 rec.dist_to_reverse=(dR===null)?null:dR.length;
 if(rd.join("")===sig.join("")){rec.flag="read_equals_signature";return rec;}
 if(rev.join("")===sig.join("")){rec.flag="palindrome_signature";return rec;}
 if(dR===null){
  if(pw.join("")===rd.join("")&&pw.join("")!==rev.join("")){rec.flag="reversed_per_word_exact";return rec;}
  rec.flag="length_mismatch";return rec;}
 if(dR.length===0){rec.flag="reversed_exact";return rec;}
 if(dF!==null&&dR.length>=dF.length){rec.flag="ambiguous_basis";return rec;}
 if(dR.length===1){var d=dR[0],i=d[0],want=d[1],got=d[2];
  rec.swap={position_in_candidate:i,reading_position:i+1,position_in_signature:rev.length-1-i,
   reverse_has:want,read_has:got,pair:rgPairName(want,got)};
  rec.registers=rgRegisters(want,got);
  rec.flag=rec.registers.length?"reversed_one_swap":"reversed_one_swap_unlisted";
  return rec;}
 if(pw.join("")===rd.join("")&&pw.join("")!==rev.join("")){rec.flag="reversed_per_word_exact";return rec;}
 return rec;}
/* The two CONSEQUENCES. One predicate, two axes: `rgRefuses` blocks the download, `rgWarns` only
   speaks. Membership comes from the generator, so adding a verdict there cannot leave it silent
   here -- the generator asserts every verdict has a consequence. */
function rgRefuses(flag){return RG_REFUSING.indexOf(flag)>=0;}
function rgWarns(flag){return RG_WARNING.indexOf(flag)>=0;}
"""


def _dump(obj):
    u"""JSON for embedding in a script block: non-ASCII escaped, so the blob is pure ASCII and its
    length is the same number whatever a reader's editor does to the Hebrew."""
    return json.dumps(obj, ensure_ascii=True, sort_keys=True, separators=(",", ":"))


def build():
    js = (_JS_TEMPLATE
          .replace("__REGISTERS__", _dump(REGISTERS))
          .replace("__PAIRNAMES__", _dump(PAIR_NAMES))
          .replace("__REFUSING__", _dump(list(REFUSING_FLAGS)))
          .replace("__WARNING__", _dump(list(WARNING_FLAGS))))
    for ph in ("__REGISTERS__", "__PAIRNAMES__", "__REFUSING__", "__WARNING__"):
        assert ph not in js, "%s was not substituted" % ph
    assert js == js.encode("ascii", "strict").decode("ascii"), \
        "the guard blob is not pure ASCII, so its blob id depends on an encoding"
    return js


GUARD_JS = build()


def guard_id(blob=None):
    u"""(length, sha16) of the guard blob.  RECORDED, never pinned: the vocabulary is allowed to
    grow, and a pin over generated code would make growing it look like tampering.  What is asserted
    is BEHAVIOUR, by the node born-test."""
    b = GUARD_JS if blob is None else blob
    b = b.strip("\n")
    return len(b), hashlib.sha256(b.encode("utf-8")).hexdigest()[:16]


if __name__ == "__main__":
    cmd = sys.argv[1] if len(sys.argv) > 1 else "id"
    if cmd == "js":
        sys.stdout.write(GUARD_JS)
    elif cmd == "id":
        n, h = guard_id()
        print("guard blob: %d chars, sha16 %s" % (n, h))
        print("pairs in vocabulary: %d" % len(REGISTERS))
        print("refusing flags: %s" % ", ".join(REFUSING_FLAGS))
        print("warning flags:  %s" % ", ".join(WARNING_FLAGS))
    else:
        sys.exit("usage: reversal_guard_js.py [id|js]")
